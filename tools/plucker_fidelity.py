#!/usr/bin/env python3
"""Plücker geometric fidelity through the video VAE, on the PRODUCTION raymap representation.

Representation (data_utils.build_raymap_latent, unmodified):
    poses -> convert_to_plucker -> d (unit) , m = o x d
    dir video = d, mom video = clamp(m / moment_scale, -1, 1)
    dir_lat = VAE.enc(dir video), mom_lat = VAE.enc(mom video)  (separately) -> concat (1, 2z, T, h, w)

This script decodes such a latent -- either built from GT poses (E1) or generated by the DiT
(E2, sample_*_pred_raymap.npy) -- dir and mom SEPARATELY, re-assembles (d^, m^) WITHOUT
renormalizing, and asks whether it is still a Plücker ray field of a pinhole camera:

  pixel  |‖d^‖-1|                          unit-norm
  pixel  |d^·m^| / ‖m^‖  (cos, ‖m^‖>thr)    the Plücker (Klein-quadric) constraint d·m = 0
         |d^·m^| [m]                        same, metric
  pixel  ∠(d^, d), ‖m^-m‖, ‖m^-m_clamped‖   reconstruction vs GT (clamp separated)
  frame  proc_resid_deg, mom_resid_m        rigidity: one R per frame, one centre o (m = o x d)
  traj   pose_errors / ATE / RPE            what the geometry means downstream
  proj_  same traj metrics after projecting m^ onto d^⊥ (m <- m - (d·m)d): does the
         constraint violation itself cost pose accuracy?

E1:  --mode gt   --data_root /root/data/carla_x        (poses.npy + intrinsics.npy per seq)
E2:  --mode pred --pred_dir <inference out dir>         (sample_*_pred_raymap.npy +
                                                        sample_*_action_poses.npy); the GT floor
                                                        for the same window is computed in-row
                                                        with prefix floor_.
Run with RAYMAP_CAM_FIX=opencv for the camfix checkpoints (read at import by both
transformer_cosmos.py and invert_raymap.py).
"""
