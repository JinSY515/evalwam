PCT = (50, 95)


def _stats(x, name, out):
    x = np.asarray(x, dtype=np.float64).ravel()
    x = x[np.isfinite(x)]
    if x.size == 0:
        out[name + "_mean"] = float("nan")
        for p in PCT:
            out["%s_p%d" % (name, p)] = float("nan")
        return
    out[name + "_mean"] = float(x.mean())
    for p, v in zip(PCT, np.percentile(x, PCT)):
        out["%s_p%d" % (name, p)] = float(v)


# ── decode: dir and mom separately, NO renormalization ─────────────────────────────────────
def decode_raw(vae, lat, lmean, lstd, moment_scale):
    """(1, 2z, T, h, w) -> d^ (T,H,W,3) raw, m^ (T,H,W,3) metric; float64."""
    import torch
    z = lat.shape[1] // 2
    with torch.no_grad():
        def _dec(l):
            mu = l / lstd + lmean
            px = vae.decode(mu.to(vae.dtype)).sample
            return px[0].permute(1, 2, 3, 0).float().cpu().numpy().astype(np.float64)
        d = _dec(lat[:, :z])
        m = _dec(lat[:, z:]) * float(moment_scale)
    return d, m


def gt_field(poses, intr4, args, device):
    """GT (d, m) with the production convert_to_plucker -- the exact tensor that was encoded."""
    import torch
    from diffusers.models.transformers.transformer_cosmos import CosmosTransformer3DModel
    Hr, Wr = args.height // args.ray_downsample, args.width // args.ray_downsample
    F = len(poses)
    # float64 here (production uses float32): this is the reference, not the encoder input
    ext = torch.from_numpy(ir.poses_to_mats(poses)).to(device=device, dtype=torch.float64)[None]
    intr = torch.tensor([float(v) for v in np.asarray(intr4).ravel()[:4]], dtype=torch.float64,
                        device=device)[None, None].expand(1, F, 4)
    pl = CosmosTransformer3DModel.convert_to_plucker(
        None, ext, intr, Hr, Wr, F, (args.width, args.height), 1, device)[0]
    pl = pl.cpu().numpy()
    return pl[..., :3], pl[..., 3:]


# ── the one evaluator shared by E1 and E2 ──────────────────────────────────────────────────
def evaluate_latent(vae, lat, lmean, lstd, poses, intr4, args, prefix="", dump=None):
    ms = args.raymap_moment_scale
    orig_wh = (args.width, args.height)
    d_hat, m_hat = decode_raw(vae, lat, lmean, lstd, ms)
    d_gt, m_gt = gt_field(poses, intr4, args, args.device)
    assert d_hat.shape == d_gt.shape, (d_hat.shape, d_gt.shape)

    row = {}
    dn = np.linalg.norm(d_hat, axis=-1)
    du = d_hat / np.maximum(dn, 1e-12)[..., None]
    mn = np.linalg.norm(m_hat, axis=-1)
    dm = np.einsum("...i,...i->...", du, m_hat)              # signed d̂u·m̂ [m]
    dm_raw = np.einsum("...i,...i->...", d_hat, m_hat)       # unnormalized d̂·m̂
    mask = mn > args.mom_thr
    cos_dm = np.abs(dm) / np.maximum(mn, 1e-12)

    ang = np.degrees(np.arccos(np.clip(np.einsum("...i,...i->...", du, d_gt), -1, 1)))
    m_err = np.linalg.norm(m_hat - m_gt, axis=-1)
    m_gt_c = np.clip(m_gt / ms, -1, 1) * ms
    m_err_c = np.linalg.norm(m_hat - m_gt_c, axis=-1)
    m_par = np.abs(dm)                                       # ‖component of m̂ along d̂‖

    _stats(np.abs(dn - 1.0), "dnorm_err", row)
    _stats(cos_dm[mask], "plucker_cos", row)
    _stats(np.abs(dm[mask]), "plucker_abs_m", row)
    _stats(np.abs(dm_raw[mask]), "plucker_raw_abs_m", row)
    _stats(ang, "dir_ang_deg", row)
    _stats(m_err, "mom_err_m", row)
    _stats(m_err_c, "mom_err_vs_clamped_m", row)
    row["plucker_mask_frac"] = float(mask.mean())
    row["mom_par_over_err"] = float(m_par.mean() / max(m_err.mean(), 1e-12))
    row["gt_mom_norm_mean_m"] = float(np.linalg.norm(m_gt, axis=-1).mean())
    row["gt_clamp_frac"] = float((np.abs(m_gt) > ms).any(-1).mean())
    # GT self-check: the reference itself must satisfy the constraint
    row["gt_plucker_abs_max"] = float(np.abs(np.einsum("...i,...i->...", d_gt, m_gt)).max())

    # rigidity + pose (invert_rays renormalizes d internally; moments raw)
    pa, _, dg = ir.invert_rays(du, m_hat, intr4, orig_wh, poses[0], ms)
    row.update(dg)
    row.update(ir.pose_errors(pa, poses))
    row.update(ir.ate_rpe(pa, poses))

    # projection onto the Plücker quadric: m <- m - (d·m) d
    m_proj = m_hat - dm[..., None] * du
    pp, _, dgp = ir.invert_rays(du, m_proj, intr4, orig_wh, poses[0], ms)
    row["proj_mom_resid_m"] = dgp["mom_resid_m"]
    e = ir.pose_errors(pp, poses, "proj_")
    row.update({k: e[k] for k in ("proj_abs_trans_err", "proj_yaw_err_deg")})
    a = ir.ate_rpe(pp, poses)
    row.update({"proj_" + k: a[k] for k in ("ate_trans_rmse_m", "ate_rot_mean_deg",
                                            "rpe1_trans_m", "rpe4_trans_m")})

    per_frame = {
        "plucker_cos": np.array([cos_dm[f][mask[f]].mean() if mask[f].any() else np.nan
                                 for f in range(len(cos_dm))]),
        "plucker_abs_m": np.abs(dm).reshape(len(dm), -1).mean(1),
        "dnorm_err": np.abs(dn - 1).reshape(len(dn), -1).mean(1),
        "dir_ang_deg": ang.reshape(len(ang), -1).mean(1),
        "mom_err_m": m_err.reshape(len(m_err), -1).mean(1),
        "rec_poses": np.asarray(pa, dtype=np.float64),      # (F,6) recovered, CARLA rows
        "gt_poses": np.asarray(poses, dtype=np.float64),
    }
    if dump is not None:
        dump["per_frame"] = per_frame
        dump["maps"] = {"plucker_abs_m": np.abs(dm).astype(np.float32),
                        "dnorm_err": np.abs(dn - 1).astype(np.float32),
                        "mom_err_m": m_err.astype(np.float32)}
    return {prefix + k: v for k, v in row.items()}, per_frame


def heatmap_png(maps, path, title, frames=(1, 20, 40, 60, 76)):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    keys = list(maps)
    T = maps[keys[0]].shape[0]
    fr = [f for f in frames if f < T]
    fig, ax = plt.subplots(len(keys), len(fr), figsize=(2.4 * len(fr), 2.4 * len(keys)),
                           squeeze=False)
    for r, k in enumerate(keys):
        vmax = float(np.percentile(maps[k][fr], 99)) or 1e-6
        for c, f in enumerate(fr):
            im = ax[r][c].imshow(maps[k][f], cmap="magma", vmin=0, vmax=vmax)
            ax[r][c].set_xticks([]); ax[r][c].set_yticks([])
            if r == 0:
                ax[r][c].set_title("frame %d" % f, fontsize=8)
            if c == 0:
                ax[r][c].set_ylabel(k, fontsize=8)
        fig.colorbar(im, ax=ax[r].tolist(), shrink=0.8)
    fig.suptitle(title, fontsize=9)
    fig.savefig(path, dpi=110)
    plt.close(fig)


# ── window sources ─────────────────────────────────────────────────────────────────────────
def gt_windows(args):
    seqs = sorted(glob.glob(os.path.join(args.data_root, "*", "*", "seq_*")))
    seqs = [s for s in seqs if os.path.exists(os.path.join(s, "poses.npy"))]
    rng = np.random.default_rng(args.seed)
    out = []
    for s in seqs:
        P = np.load(os.path.join(s, "poses.npy")).astype(np.float64)
        intr = np.load(os.path.join(s, "intrinsics.npy")).astype(np.float64).ravel()[:4]
        n = len(P) - args.num_frames + 1
        if n <= 0:
            continue
        starts = rng.choice(n, size=min(args.windows_per_seq, n), replace=False)
        for st in sorted(starts):
            rel = os.path.relpath(s, args.data_root)
            out.append({"id": "%s@%d" % (rel, st), "seq": rel, "start": int(st),
                        "poses": P[st:st + args.num_frames], "intr": intr, "lat": None})
    if args.max_windows:
        idx = rng.permutation(len(out))[:args.max_windows]
        out = [out[i] for i in sorted(idx)]
    return out


def pred_windows(args):
    meta_p = os.path.join(args.pred_dir, "samples_meta.json")
    meta = json.load(open(meta_p)) if os.path.exists(meta_p) else {}
    override = ([float(v) for v in args.intrinsics_override.split(",")]
                if args.intrinsics_override else None)
    out = []
    for pf in sorted(glob.glob(os.path.join(args.pred_dir, "sample_*_action_poses.npy"))):
        rp = pf.replace("_action_poses.npy", "_pred_raymap.npy")
        if not os.path.exists(rp):
            continue
        tag = os.path.basename(pf).replace("_action_poses.npy", "")
        idx = str(int(tag.split("_")[1]))
        intr = override
        sd = (meta.get(idx) or {}).get("seq_dir")
        if intr is None and sd and os.path.exists(os.path.join(sd, "intrinsics.npy")):
            intr = np.load(os.path.join(sd, "intrinsics.npy")).ravel()[:4]
        if intr is None:
            print("[%s] skip: no intrinsics" % tag)
            continue
        out.append({"id": tag, "seq": sd or "", "start": -1,
                    "poses": np.load(pf).astype(np.float64), "intr": np.asarray(intr, float),
                    "lat": rp})
    if args.max_windows:
        out = out[:args.max_windows]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["gt", "pred"], required=True)
    ap.add_argument("--data_root", default="/root/data/carla_x")
    ap.add_argument("--pred_dir", default=None)
    ap.add_argument("--out_dir", default="/root/project/egowam/results_syn/plucker_fidelity")
    ap.add_argument("--tag", default=None)
    ap.add_argument("--windows_per_seq", type=int, default=1)
    ap.add_argument("--max_windows", type=int, default=0)
    ap.add_argument("--shard", default="0/1")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--height", type=int, default=512)
    ap.add_argument("--width", type=int, default=512)
    ap.add_argument("--num_frames", type=int, default=77)
    ap.add_argument("--ray_downsample", type=int, default=2)
    ap.add_argument("--raymap_moment_scale", type=float, default=8.0)
    ap.add_argument("--mom_thr", type=float, default=0.05, help="‖m^‖ mask for the cos metric [m]")
    ap.add_argument("--model_name", default="nvidia/Cosmos-Predict2.5-2B")
    ap.add_argument("--revision", default="diffusers/base/post-trained")
    ap.add_argument("--dtype", default="bf16", choices=["bf16", "fp16", "fp32"])
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--intrinsics_override", default=None)
    ap.add_argument("--n_heatmaps", type=int, default=6)
    ap.add_argument("--self_ref", action="store_true",
                    help="pred mode: also score vs the raymap of its own recovered camera")
    args = ap.parse_args()

    import torch
    tag = args.tag or args.mode
    os.makedirs(args.out_dir, exist_ok=True)
    k, n = [int(v) for v in args.shard.split("/")]
    sfx = "" if n == 1 else "_shard%dof%d" % (k, n)
    csv_path = os.path.join(args.out_dir, "%s%s.csv" % (tag, sfx))
    pf_path = os.path.join(args.out_dir, "%s%s_per_frame.npz" % (tag, sfx))
    hm_dir = os.path.join(args.out_dir, "heatmaps_%s" % tag)
    os.makedirs(hm_dir, exist_ok=True)

    print("[cfg] mode %s  RAYMAP_CAM_FIX %s  vae %s@%s %s  moment_scale %g"
          % (args.mode, "ON" if ir._CAM_FIX else "OFF", args.model_name, args.revision,
             args.dtype, args.raymap_moment_scale))
    if not ir._CAM_FIX:
        print("[warn] RAYMAP_CAM_FIX is off -- the camfix checkpoints were trained with it on")

    wins = gt_windows(args) if args.mode == "gt" else pred_windows(args)
    wins = wins[k::n]
    print("[cfg] %d windows (shard %s)" % (len(wins), args.shard))
    vae, lmean, lstd = ir.load_vae(args.model_name, args.revision, args.device, args.dtype)
    t_lat = (args.num_frames - 1) // 4 + 1
    hr = args.height // args.ray_downsample // 8

    rows, pfs = [], {}
    for i, w in enumerate(wins):
        t0 = time.time()
        if len(w["poses"]) != args.num_frames:
            print("[%s] skip: %d poses" % (w["id"], len(w["poses"])))
            continue
        row = {"id": w["id"], "seq": w["seq"], "start": w["start"], "cam_fix": int(ir._CAM_FIX)}
        with torch.no_grad():
            gt_lat = ir.build_gt_latent(vae, lmean, lstd, w["poses"], w["intr"], args, args.device)
        assert tuple(gt_lat.shape[2:]) == (t_lat, hr, hr), gt_lat.shape
        dump = {} if i < args.n_heatmaps else None
        if args.mode == "gt":
            r, pf = evaluate_latent(vae, gt_lat, lmean, lstd, w["poses"], w["intr"], args,
                                    dump=dump)
            row.update(r)
        else:
            lat = torch.from_numpy(np.load(w["lat"])).to(args.device).float()
            if lat.ndim == 4:
                lat = lat[None]
            assert lat.shape == gt_lat.shape, \
                "[%s] pred_raymap %s vs gt latent %s" % (w["id"], tuple(lat.shape),
                                                         tuple(gt_lat.shape))
            r, pf = evaluate_latent(vae, lat, lmean, lstd, w["poses"], w["intr"], args,
                                    dump=dump)
            row.update(r)
            rf, _ = evaluate_latent(vae, gt_lat, lmean, lstd, w["poses"], w["intr"], args,
                                    prefix="floor_")
            row.update(rf)
            row["trans_above_floor"] = bool(row["floor_abs_trans_err"] < row["abs_trans_err"] / 3)
            row["lat_rel_err"] = float((lat - gt_lat).norm() / gt_lat.norm())
            if args.self_ref:
                # self reference. The generated field vs its OWN best-fit camera is already in
                # proc_resid_deg / mom_resid_m (invert_frame: per-frame Procrustes + o solve, no
                # frame-0 gauge). selffloor_ = E1 on the generated trajectory: the clean raymap of
                # the recovered poses through VAE encode-decode -> the floor for those residuals.
                sp = pf["rec_poses"]
                with torch.no_grad():
                    s_lat = ir.build_gt_latent(vae, lmean, lstd, sp, w["intr"], args, args.device)
                rsf, _ = evaluate_latent(vae, s_lat, lmean, lstd, sp, w["intr"], args,
                                         prefix="selffloor_")
                row.update(rsf)
        for kk, v in pf.items():
            pfs.setdefault(kk, []).append(v)
        if dump is not None:
            heatmap_png(dump["maps"], os.path.join(hm_dir, "%s.png" % w["id"].replace("/", "_")),
                        "%s  [%s]  plucker_cos p50 %.4f  ATE %.3f m"
                        % (w["id"], tag, row["plucker_cos_p50"], row["ate_trans_rmse_m"]))
        rows.append(row)
        ir._ecc()._write_csv(rows, csv_path)
        print("[%d/%d %s] |d|-1 %.2e  cos(d,m) p50 %.4f p95 %.4f  ang %.3f°  m_err %.4f m  "
              "mom_resid %.4f m  ATE %.4f m (proj %.4f)  rot %.3f°  %.1fs"
              % (i + 1, len(wins), w["id"], row["dnorm_err_mean"], row["plucker_cos_p50"],
                 row["plucker_cos_p95"], row["dir_ang_deg_mean"], row["mom_err_m_mean"],
                 row["mom_resid_m"], row["ate_trans_rmse_m"], row["proj_ate_trans_rmse_m"],
                 row["ate_rot_mean_deg"], time.time() - t0))
    np.savez(pf_path, ids=np.array([r["id"] for r in rows]),
             **{kk: np.stack(v) for kk, v in pfs.items()})
    print("[done] %s  %s" % (csv_path, pf_path))


if __name__ == "__main__":
    main()
